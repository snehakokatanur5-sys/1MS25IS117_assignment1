import { StructuredPaperDraft, PeerReviewResult, PaperRequest, PromptConfigResponse } from '../types/research';

export function generatePaperTxt(
  draft: StructuredPaperDraft,
  request?: PaperRequest,
  review?: PeerReviewResult
): string {
  const divider = '='.repeat(80);
  const subDivider = '-'.repeat(80);

  let output = `${divider}\n`;
  output += `${draft.title.toUpperCase()}\n`;
  if (request) {
    output += `Academic Field: ${request.field}\n`;
    output += `Target Scope: ${request.length.toUpperCase()} ARTICLE\n`;
  }
  output += `Generated by ScholarForge AI Research Paper Agent\n`;
  output += `${divider}\n\n`;

  output += `ABSTRACT\n${subDivider}\n${draft.abstract}\n\n`;
  output += `KEYWORDS: ${draft.keywords.join(', ')}\n\n`;

  output += `1. INTRODUCTION\n${subDivider}\n${draft.introduction}\n\n`;

  output += `2. RESEARCH OBJECTIVES & HYPOTHESES\n${subDivider}\n${draft.researchObjectives}\n\n`;

  output += `3. LITERATURE REVIEW\n${subDivider}\n${draft.literatureReview}\n\n`;

  output += `4. METHODOLOGY & EXPERIMENTAL DESIGN\n${subDivider}\n${draft.methodology}\n\n`;

  output += `5. FINDINGS & EMPIRICAL DISCUSSION\n${subDivider}\n${draft.findings}\n\n`;

  output += `6. CONCLUSION, LIMITATIONS & FUTURE WORK\n${subDivider}\n${draft.conclusion}\n\n`;

  output += `REFERENCES\n${subDivider}\n`;
  draft.references.forEach((ref, idx) => {
    output += `[${idx + 1}] ${ref}\n`;
  });
  output += `\n`;

  if (review) {
    output += `${divider}\n`;
    output += `INDEPENDENT PEER REVIEW REPORT\n`;
    output += `${divider}\n`;
    output += `Recommendation: ${review.recommendation}\n`;
    output += `Overall Scholarly Score: ${review.overallScore} / 10.0\n\n`;
    output += `Criteria Evaluation:\n`;
    output += `  - Methodological Rigor: ${review.criteriaScores.methodologicalRigor} / 10\n`;
    output += `  - Theoretical Depth:    ${review.criteriaScores.theoreticalDepth} / 10\n`;
    output += `  - Structural Clarity:   ${review.criteriaScores.structuralClarity} / 10\n`;
    output += `  - Literature Synthesis: ${review.criteriaScores.literatureSynthesis} / 10\n\n`;

    output += `Key Scholarly Strengths:\n`;
    review.keyStrengths.forEach(s => {
      output += `  • ${s}\n`;
    });
    output += `\nSuggested Refinements:\n`;
    review.suggestedRevisions.forEach(r => {
      output += `  • ${r}\n`;
    });
    output += `\nEthical & Governance Considerations:\n${review.ethicalConsiderations}\n\n`;
    output += `Referee Concluding Remarks:\n${review.concludingRemarks}\n`;
    output += `${divider}\n`;
  }

  return output;
}

export function downloadFile(content: string, filename: string, mimeType: string = 'text/plain') {
  const blob = new Blob([content], { type: `${mimeType};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function generateBibtex(draft: StructuredPaperDraft): string {
  const cleanKey = draft.title
    .replace(/[^a-zA-Z0-9 ]/g, '')
    .split(' ')
    .slice(0, 3)
    .join('')
    .toLowerCase() + new Date().getFullYear();

  let bib = `@article{${cleanKey},\n`;
  bib += `  title = {${draft.title}},\n`;
  bib += `  author = {ScholarForge Academic Agent},\n`;
  bib += `  journal = {Journal of Advanced Multidisciplinary Research},\n`;
  bib += `  year = {${new Date().getFullYear()}},\n`;
  bib += `  keywords = {${draft.keywords.join(', ')}}\n`;
  bib += `}\n\n`;

  bib += `% Cited Reference Records:\n`;
  draft.references.forEach((ref, idx) => {
    bib += `% [${idx + 1}] ${ref}\n`;
  });

  return bib;
}
